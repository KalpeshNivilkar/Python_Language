marks = [10,34,22,55,6,54,76,33]
# list length
print(len(marks))
# list individual print 
print(marks[4])
# list print 
print(marks)
# list mutable 
marks[4] = 90
# print updated list 
print(marks)
# append method 
marks.append(28)
print(marks)
# sort method 
marks.sort()
print(marks)
# sort reverse method
marks.sort(reverse=True)
print(marks)
marks.reverse()
print(marks)
marks.insert(5,58)
print(marks)